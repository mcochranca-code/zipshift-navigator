import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const inputDir = path.resolve(root, process.env.MYSQL_MIGRATIONS_DIR || "server/migrations");
const outputDir = path.resolve(root, process.env.COCKROACH_MIGRATIONS_DIR || "db/cockroach-migrations");

const unsupportedPatterns: Array<[RegExp, string]> = [
  [/ON\s+DUPLICATE\s+KEY/i, "ON DUPLICATE KEY requires an explicit upsert conflict target"],
  [/INSERT\s+IGNORE/i, "INSERT IGNORE requires explicit conflict/error semantics"],
  [/REPLACE\s+INTO/i, "REPLACE INTO requires an explicit upsert strategy"],
  [/\bENUM\s*\(/i, "ENUM requires an explicit CHECK constraint or lookup table"],
  [/\bFULLTEXT\b/i, "FULLTEXT indexes require a Cockroach-compatible search design"],
  [/\bSPATIAL\b/i, "SPATIAL indexes require a reviewed geography strategy"],
  [/\bTRIGGER\b/i, "Triggers require an application/outbox replacement"],
  [/\bPROCEDURE\b/i, "Stored procedures must be replaced by application services"],
  [/\bDELIMITER\b/i, "Client-side DELIMITER directives are not Cockroach SQL"],
];

function translateSql(source: string, filename: string) {
  const warnings: string[] = [];
  for (const [pattern, message] of unsupportedPatterns) {
    if (pattern.test(source)) warnings.push(`${filename}: ${message}`);
  }

  let sql = source
    .replace(/\/\*[\s\S]*?\*\//g, (comment) => comment)
    .replace(/`([^`]+)`/g, '"$1"')
    .replace(/\bENGINE\s*=\s*[^;\n]+/gi, "")
    .replace(/\bDEFAULT\s+CHARSET\s*=\s*[^;\n]+/gi, "")
    .replace(/\bCHARSET\s*=\s*[^;\n]+/gi, "")
    .replace(/\bCOLLATE\s*=\s*[^;\n]+/gi, "")
    .replace(/\bUNSIGNED\b/gi, "")
    .replace(/\bZEROFILL\b/gi, "")
    .replace(/\bTINYINT\s*\(\s*1\s*\)/gi, "BOOLEAN")
    .replace(/\bMEDIUMTEXT\b|\bLONGTEXT\b/gi, "TEXT")
    .replace(/\bDATETIME(?:\s*\(\s*\d+\s*\))?\b/gi, "TIMESTAMPTZ")
    .replace(/\bJSON\b/gi, "JSONB")
    .replace(/\bDEFAULT\s+CURRENT_TIMESTAMP\s*\(\s*\)/gi, "DEFAULT now()")
    .replace(/\bON\s+UPDATE\s+CURRENT_TIMESTAMP\s*\(\s*\)/gi, "")
    .replace(/\bON\s+UPDATE\s+CURRENT_TIMESTAMP\b/gi, "")
    .replace(/\s+AFTER\s+[A-Za-z0-9_"`]+/gi, "")
    .replace(/\bAUTO_INCREMENT\b/gi, "GENERATED BY DEFAULT AS IDENTITY")
    .replace(/\bUNIQUE\s+KEY\b/gi, "UNIQUE INDEX")
    .replace(/\bKEY\s+([A-Za-z0-9_"`]+)\s*\(/gi, "INDEX $1 (")
    .replace(/ALTER\s+TABLE\s+([A-Za-z0-9_"`]+)\s+ADD\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z0-9_"`]+)\s*\(([^;]+)\)\s*;/gi,
      "CREATE INDEX IF NOT EXISTS $2 ON $1 ($3);")
    .replace(/ALTER\s+TABLE\s+([A-Za-z0-9_"`]+)\s+ADD\s+UNIQUE\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z0-9_"`]+)\s*\(([^;]+)\)\s*;/gi,
      "CREATE UNIQUE INDEX IF NOT EXISTS $2 ON $1 ($3);")
    .replace(/\n\s*,/g, "\n,")
    .replace(/,\s*\)/g, "\n)");

  if (/\bFIELD\s*\(/i.test(sql)) warnings.push(`${filename}: FIELD(...) is a query-time MySQL function and must be rewritten in API SQL`);
  if (/JSON_EXTRACT/i.test(sql)) warnings.push(`${filename}: JSON_EXTRACT is a query-time MySQL function and must be rewritten with Cockroach JSONB operators`);
  if (/\bKEY\s+[A-Za-z0-9_"`]+\s*\(/i.test(sql)) warnings.push(`${filename}: inline KEY definitions require manual index review`);
  if (/\bCHAR\s*\(\s*36\s*\)/i.test(sql)) warnings.push(`${filename}: CHAR(36) identifiers are preserved for compatibility; native UUID conversion is deferred`);

  return { sql, warnings };
}

async function main() {
  const files = (await readdir(inputDir)).filter((file) => file.endsWith(".sql")).sort();
  if (!files.length) throw new Error(`No SQL migrations found in ${inputDir}`);

  await mkdir(outputDir, { recursive: true });
  const manifest: { generatedAt: string; inputDir: string; outputDir: string; files: Array<{ source: string; output: string; sha256: string; warnings: string[] }> } = {
    generatedAt: new Date().toISOString(),
    inputDir: path.relative(root, inputDir),
    outputDir: path.relative(root, outputDir),
    files: [],
  };
  const allWarnings: string[] = [];

  for (const file of files) {
    const source = await readFile(path.join(inputDir, file), "utf8");
    const result = translateSql(source, file);
    const outputName = file.replace(/\.sql$/i, ".cockroach.sql");
    const header = [
      "-- GENERATED CANDIDATE DDL: review before applying to CockroachDB.",
      `-- Source migration: ${file}`,
      "-- This file was generated offline; it does not connect to or mutate any database.",
      "-- Warnings are recorded in db/cockroach-migrations/manifest.json.",
      "",
    ].join("\n");
    await writeFile(path.join(outputDir, outputName), `${header}${result.sql.trim()}\n`, "utf8");
    const sha256 = createHash("sha256").update(source).digest("hex");
    manifest.files.push({ source: file, output: outputName, sha256, warnings: result.warnings });
    allWarnings.push(...result.warnings);
  }

  await writeFile(path.join(outputDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  console.log(`Translated ${files.length} migration files into ${path.relative(root, outputDir)}.`);
  if (allWarnings.length) {
    console.warn(`Manual review required: ${allWarnings.length} warning(s).`);
    for (const warning of allWarnings) console.warn(`- ${warning}`);
  }
  if (process.argv.includes("--check") && allWarnings.length) process.exitCode = 2;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
